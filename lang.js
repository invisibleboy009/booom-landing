function setLanguage(lang) {
  if (!translations[lang]) return;

  const t = translations[lang];

  document.documentElement.setAttribute('lang', lang === 'UK' ? 'uk' : lang.toLowerCase());
  document.documentElement.setAttribute('data-lang', lang);

  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    const key = el.getAttribute('data-i18n');
    if (t[key] === undefined) return;
    const value = String(t[key]);

    // A handful of headlines carry a deliberate line break as a literal "<br>" in the
    // string. textContent printed it as four visible characters — every visitor, in all
    // six languages, read "BOOOM nie je appka pre ľudí,<br>čo sa chodia do fitka fotiť."
    //
    // Split and build real <br> elements rather than switching to innerHTML: the strings
    // are ours today, but an applier that renders markup is one copy-pasted translation
    // away from executing it, and nothing else here needs that power.
    if (value.indexOf('<br>') === -1) {
      el.textContent = value;
      return;
    }
    el.textContent = '';
    value.split('<br>').forEach(function (part, i) {
      if (i > 0) el.appendChild(document.createElement('br'));
      el.appendChild(document.createTextNode(part));
    });
  });

  document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
    const key = el.getAttribute('data-i18n-aria');
    if (t[key] !== undefined) {
      el.setAttribute('aria-label', t[key]);
    }
  });

  // TikTok is two accounts: one posting in Slovak, one in English. Sending a German or
  // Polish visitor to a feed they cannot read earns a follow and then an unfollow, so the
  // link follows the language rather than the domain. Czech goes to the Slovak account on
  // purpose — close enough that the content lands. Instagram is a single account.
  var tiktokUrl = (lang === 'SK' || lang === 'CS')
    ? 'https://www.tiktok.com/@booom.fitness.app'
    : 'https://www.tiktok.com/@getbooom';
  document.querySelectorAll('[data-tiktok]').forEach(function (el) {
    el.setAttribute('href', tiktokUrl);
  });

  document.querySelectorAll('.lang-btn').forEach(function (btn) {
    btn.classList.toggle('active', btn.textContent.trim() === lang);
  });

  // Compact language switcher (index header): reflect the current language on the toggle.
  var langCode = document.getElementById('langCode');
  if (langCode) langCode.textContent = lang;

  document.title = pageTitles[lang] || pageTitles['SK'];

  try {
    localStorage.setItem('booom_lang', lang);
  } catch (e) {}
}

(function () {
  var saved;
  try { saved = localStorage.getItem('booom_lang'); } catch (e) {}
  if (saved && translations[saved]) {
    setLanguage(saved);
  } else {
    var browserLang = (navigator.language || navigator.userLanguage || '').toLowerCase();
    if (browserLang.startsWith('de')) setLanguage('DE');
    else if (browserLang.startsWith('pl')) setLanguage('PL');
    else if (browserLang.startsWith('uk')) setLanguage('UK');
    else if (browserLang.startsWith('cs')) setLanguage('CS');
    else if (browserLang.startsWith('sk')) setLanguage('SK');
    else if (browserLang.startsWith('en')) setLanguage('EN');
    else setLanguage('SK'); // default
  }
}());
